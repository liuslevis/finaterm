def shade(cell, color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), color)
    tcPr.append(shd)


def set_cell_margins(table, top=40, bottom=40, left=70, right=70):
    tblPr = table._tbl.tblPr
    mar = OxmlElement("w:tblCellMar")
    for k, v in (("top", top), ("bottom", bottom), ("left", left), ("right", right)):
        el = OxmlElement(f"w:{k}")
        el.set(qn("w:w"), str(v))
        el.set(qn("w:type"), "dxa")
        mar.append(el)
    tblPr.append(mar)


def table(headers, rows, widths, font_size=8.6, header_bg="1F3A5F", first_col_bold=False,
          highlight_rows=(), highlight_color="F3F6FA"):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.style = "Table Grid"
    t.autofit = False
    set_cell_margins(t)
    hdr = t.rows[0].cells
    trPr = t.rows[0]._tr.get_or_add_trPr()
    tblHeader = OxmlElement("w:tblHeader")
    tblHeader.set(qn("w:val"), "true")
    trPr.append(tblHeader)
    cant_h = OxmlElement("w:cantSplit")
    cant_h.set(qn("w:val"), "true")
    trPr.append(cant_h)
    for i, htext in enumerate(headers):
        hdr[i].width = Cm(widths[i])
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(1)
        r = p.add_run(str(htext))
        cn(r, name="微软雅黑", size=font_size, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF))
        shade(hdr[i], header_bg)
    for ridx, row in enumerate(rows):
        new_row = t.add_row()
        cells = new_row.cells
        row_trPr = new_row._tr.get_or_add_trPr()
        cant = OxmlElement("w:cantSplit")
        cant.set(qn("w:val"), "true")
        row_trPr.append(cant)
        for i, val in enumerate(row):
            cells[i].width = Cm(widths[i])
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if i == 0 else WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.line_spacing = 1.0
            r = p.add_run(str(val))
            bold = (i == 0 and first_col_bold) or (ridx in highlight_rows)
            cn(r, name="宋体", size=font_size, bold=bold, color=BLACK)
            if ridx in highlight_rows:
                shade(cells[i], highlight_color)
    for cell in t.rows[-1].cells:
        for p in cell.paragraphs:
            p.paragraph_format.keep_with_next = True
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t



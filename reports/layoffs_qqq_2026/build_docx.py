def cn(run, name="宋体", size=10.5, bold=False, color=BLACK, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = color
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)


def para(text, size=10.5, color=BLACK, bold=False, first_indent=True, space_after=5,
         line=1.45, align=WD_ALIGN_PARAGRAPH.JUSTIFY, name="宋体"):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.line_spacing = line
    pf.space_after = Pt(space_after)
    if first_indent:
        pf.first_line_indent = Pt(size * 2)
    r = p.add_run(text)
    cn(r, name=name, size=size, color=color, bold=bold)
    return p


def lead(label, text, size=10.5):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.line_spacing = 1.45
    p.paragraph_format.space_after = Pt(5)
    p.paragraph_format.first_line_indent = Pt(size * 2)
    r1 = p.add_run(label)
    cn(r1, size=size, bold=True, color=NAVY)
    r2 = p.add_run(text)
    cn(r2, size=size, color=BLACK)
    return p


def bullet(text, size=10.5, color=BLACK, bold_lead=None):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.line_spacing = 1.4
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.left_indent = Cm(0.75)
    if bold_lead:
        r0 = p.add_run(bold_lead)
        cn(r0, size=size, bold=True, color=NAVY)
    r = p.add_run(text)
    cn(r, size=size, color=color)
    return p



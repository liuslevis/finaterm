def opec_window(index: pd.DatetimeIndex, before: int = 2, after: int = 1) -> pd.Series:
    """会议前 before 个交易日到会后 after 个交易日为 True（以会议当天或之后的首个交易日为基准）。"""
    mask = pd.Series(False, index=index)
    for d in OPEC_MEETINGS:
        i0 = index.searchsorted(d)
        if i0 >= len(index):
            continue
        mask.iloc[max(i0 - before, 0): i0 + after + 1] = True
    return mask
